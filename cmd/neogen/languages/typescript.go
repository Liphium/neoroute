const tsModelFileName = "models.ts"

func NewTSConfig() engine.LanguageConfig {
	return engine.LanguageConfig{
		Name:    "typescript",
		GetType: GetTSType,
		Funcs: template.FuncMap{
			"quote":    strconv.Quote,
			"access":   func(value, field string) string { return value + "[" + strconv.Quote(field) + "]" },
			"wireType": getTSWireType,
			"toWire":   func(p neoschema.PackedType, value string) string { return tsConvert(p, value, true, 0) },
			"fromWire": func(p neoschema.PackedType, value string) string { return tsConvert(p, value, false, 0) },
		},
		GetFileMap: func(schema neoschema.Schema) (map[string]engine.TemplateData, error) {
			files := make(map[string]engine.TemplateData)

			registry := schema.GetCombinedObjectRegistry()
			files[tsModelFileName] = engine.TemplateData{
				Template: TSObjectsTemplate,
				Object: map[string]any{
					"Registry": registry,
				},
			}

			for name, transport := range schema.Transporters {
				typeName := "HTTP"
				if transport.Type == neoschema.TransporterWebSocket {
					typeName = "WebSocket"
				}

				tData := struct {
					Name       string
					Type       string
					TypeName   string
					Routes     map[string]neoschema.RouteSchema
					Events     map[string]neoschema.PackedType
					Const      map[string]neoschema.SendType
					HasObjects bool
					Registry   map[string]neoschema.PackedType
				}{
					Name:       util.ToCamelCase(name+"Connector", true),
					Type:       strings.ToLower(string(typeName)),
					TypeName:   typeName,
					Routes:     transport.Routes,
					Events:     transport.Events,
					Const:      neoschema.SendTypeMap(),
					HasObjects: len(registry) > 0,
					Registry:   registry,
				}

				files["connector_"+strings.ToLower(name)+".ts"] = engine.TemplateData{
					Template: TSTransporterTemplate,
					Object:   tData,
				}
			}

			return files, nil
		},
	}
}

// getTSWireType follows references without expanding them, so recursive models stay finite.
func getTSWireType(p neoschema.PackedType) (string, error) {
	switch t := p.(type) {
	case *neoschema.StructType:
		return util.ToCamelCase(t.Name, true) + "Wire", nil
	case *neoschema.ReferenceType:
		return util.ToCamelCase(t.Object, true) + "Wire", nil
	case *neoschema.ArrayType:
		if t.Element.Type() == neoschema.TypeByte {
			return "Uint8Array", nil
		}
		e, err := getTSWireType(t.Element)
		return "(" + e + ")[]", err
	case *neoschema.NullableType:
		e, err := getTSWireType(t.Element)
		return e + " | null", err
	case *neoschema.MapType:
		k, err := GetTSType(t.Key)
		if err != nil {
			return "", err
		}
		v, err := getTSWireType(t.Value)
		return "Record<" + k + ", " + v + ">", err
	default:
		return GetTSType(p)
	}
}

// tsConvert transforms only schema-known containers. Bytes, dates and opaque serializable values retain the representation used by the MessagePack codec.
func tsConvert(p neoschema.PackedType, value string, toWire bool, depth int) string {
	prefix := "from"
	if toWire {
		prefix = "to"
	}
	switch t := p.(type) {
	case *neoschema.StructType:
		return prefix + util.ToCamelCase(t.Name, true) + "Wire(" + value + ")"
	case *neoschema.ReferenceType:
		return prefix + util.ToCamelCase(t.Object, true) + "Wire(" + value + ")"
	case *neoschema.NullableType:
		return "(" + value + " == null ? " + value + " : " + tsConvert(t.Element, value, toWire, depth+1) + ")"
	case *neoschema.ArrayType:
		if t.Element.Type() == neoschema.TypeByte {
			return value
		}
		item := fmt.Sprintf("item%d", depth)
		return value + ".map((" + item + ") => " + tsConvert(t.Element, item, toWire, depth+1) + ")"
	case *neoschema.MapType:
		item := fmt.Sprintf("item%d", depth)
		// Schemas only allow string map keys.
		return "Object.fromEntries(Object.entries(" + value + ").map(([key, " + item + "]) => [key, " + tsConvert(t.Value, item, toWire, depth+1) + "]))"
	default:
		return value
	}
}
