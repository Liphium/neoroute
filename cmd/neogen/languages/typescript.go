var tsTypeMap = map[neoschema.SchemaType]string{
	neoschema.TypeBool:         "boolean",
	neoschema.TypeByte:         "number",
	neoschema.TypeInt32:        "number",
	neoschema.TypeInt64:        "bigint",
	neoschema.TypeFloat32:      "number",
	neoschema.TypeFloat64:      "number",
	neoschema.TypeString:       "string",
	neoschema.TypeDate:         "Date",
	neoschema.TypeSerializable: "any",
}

func GetTSType(packed neoschema.PackedType) (string, error) {
	switch schema := packed.(type) {
	case *neoschema.StructType:
		return util.ToCamelCase(schema.Name, true), nil
	case *neoschema.ReferenceType:
		return util.ToCamelCase(schema.Object, true), nil
	case *neoschema.ArrayType:
		// Byte array → Uint8Array for proper typed array in TS/JS
		if schema.Element.Type() == neoschema.TypeByte {
			return "Uint8Array", nil
		}
		elem, err := GetTSType(schema.Element)
		if err != nil {
			return "", err
		}
		if strings.Contains(elem, " | ") {
			elem = "(" + elem + ")"
		}
		return elem + "[]", nil
	case *neoschema.MapType:
		k, err := GetTSType(schema.Key)
		if err != nil {
			return "", err
		}
		v, err := GetTSType(schema.Value)
		if err != nil {
			return "", err
		}
		return "Record<" + k + ", " + v + ">", nil
	case *neoschema.NullableType:
		elem, err := GetTSType(schema.Element)
		if err != nil {
			return "", err
		}
		return elem + " | null", nil
	default:
		t, ok := tsTypeMap[schema.Type()]
		if !ok {
			return "", fmt.Errorf("unknown type: %s", schema.Type())
		}
		return t, nil
	}
}

// TSObjectsTemplate keeps the public models separate from their MessagePack shapes.
const TSObjectsTemplate = `// Code generated by neogen v2. DO NOT EDIT.

{{ range $name, $obj := .Object.Registry }}
{{- $struct := toStruct $obj -}}
{{- if $struct }}
export interface {{ camel $name true }} {
{{- range $field := $struct.Fields }}
	{{ quote $field.Name }}: {{ getType $field.Type }};
{{- end }}
};

export type {{ camel $name true }}Wire = {{ if $struct.Tuple }}[
{{- range $i, $field := $struct.Fields }}
	field{{ $i }}: {{ wireType $field.Type }},
{{- end }}
]{{ else }}{
{{- range $field := $struct.Fields }}
	{{ quote $field.Name }}: {{ wireType $field.Type }};
{{- end }}
}{{ end }};

export function to{{ camel $name true }}Wire(value: {{ camel $name true }}): {{ camel $name true }}Wire {
	return {{ if $struct.Tuple }}[
{{- range $field := $struct.Fields }}
		{{ toWire $field.Type (access "value" $field.Name) }},
{{- end }}
	]{{ else }}{
{{- range $field := $struct.Fields }}
		{{ quote $field.Name }}: {{ toWire $field.Type (access "value" $field.Name) }},
{{- end }}
	}{{ end }};
}

export function from{{ camel $name true }}Wire(value: {{ camel $name true }}Wire): {{ camel $name true }} {
{{- if $struct.Tuple }}
	const [{{ range $i, $field := $struct.Fields }}{{ if $i }}, {{ end }}field{{ $i }}{{ end }}] = value;
{{- end }}
	return {
{{- range $i, $field := $struct.Fields }}
		{{ quote $field.Name }}: {{ if $struct.Tuple }}{{ fromWire $field.Type (printf "field%d" $i) }}{{ else }}{{ fromWire $field.Type (access "value" $field.Name) }}{{ end }},
{{- end }}
	};
}
{{- end }}
{{ end }}`

